def _add(items: dict[int, dict[str, Any]], category_id: int, weight: float, reason: str) -> None:
    if category_id not in CATEGORY_BY_ID:
        return
    current = items.get(category_id)
    if current is None or current["weight"] < weight:
        items[category_id] = {
            "category_id": category_id,
            "weight": weight,
            "rationale": reason,
        }


